// POST handler
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if (($_POST['csrf'] ?? '') !== $_SESSION['install_csrf']) {
        $err = 'CSRF token sai. Reload và thử lại.';
    } else {
        $posted = (int)($_POST['step'] ?? 0);

        // STEP 2 → 3: save DB config + test
        if ($posted === 2) {
            $db = [
                'host' => trim($_POST['db_host'] ?? '127.0.0.1'),
                'name' => trim($_POST['db_name'] ?? ''),
                'user' => trim($_POST['db_user'] ?? ''),
                'pass' => (string)($_POST['db_pass'] ?? ''),
            ];
            $r = testDbConnection($db['host'], $db['name'], $db['user'], $db['pass']);
            if (!$r['ok']) {
                $err = 'Kết nối DB thất bại: ' . $r['err'];
            } else {
                $_SESSION['install_data']['db'] = $db;
                header('Location: install.php?step=3'); exit;
            }
        }

        // STEP 3 → 4: import schema
        if ($posted === 3) {
            $db = $_SESSION['install_data']['db'] ?? null;
            if (!$db) { $err = 'Mất config DB. Quay lại step 2.'; }
            else {
                $r = testDbConnection($db['host'], $db['name'], $db['user'], $db['pass']);
                if (!$r['ok']) { $err = 'Reconnect DB fail: ' . $r['err']; }
                else {
                    $imp = importSqlFile($r['pdo'], $sqlFile);
                    if (!$imp['ok']) { $err = 'Import schema lỗi: ' . $imp['err']; }
                    else {
                        $_SESSION['install_data']['imported'] = $imp['count'];
                        header('Location: install.php?step=4'); exit;
                    }
                }
            }
        }

        // STEP 4 → 5: admin user + secrets + write config
        if ($posted === 4) {
            $adminUser = trim($_POST['admin_user'] ?? '');
            $adminPass = (string)($_POST['admin_pass'] ?? '');
            $siteUrl   = trim($_POST['site_url'] ?? '');
            $siteName  = trim($_POST['site_name'] ?? 'HCLOU License');

            if (strlen($adminUser) < 3 || strlen($adminUser) > 32 || !preg_match('/^[A-Za-z0-9_]+$/', $adminUser)) {
                $err = 'Username admin: 3-32 ký tự, chỉ A-Z a-z 0-9 _';
            } elseif (strlen($adminPass) < 8) {
                $err = 'Password ít nhất 8 ký tự';
            } elseif (!preg_match('#^https?://#i', $siteUrl)) {
                $err = 'Site URL phải bắt đầu http:// hoặc https://';
            } else {
                $db = $_SESSION['install_data']['db'];
                $config = [
                    'DB_HOST'         => $db['host'],
                    'DB_NAME'         => $db['name'],
                    'DB_USER'         => $db['user'],
                    'DB_PASS'         => $db['pass'],
                    'SITE_URL'        => rtrim($siteUrl, '/'),
                    'SITE_NAME'       => $siteName,
                    'STATIC_WORD'     => genToken(16),  // 32 hex chars
                    'HMAC_SECRET'     => genToken(32),  // 64 hex chars
                    'BODY_XOR_BASE'   => genToken(24),  // 48 hex chars
                    'ADMIN_USERNAME'  => $adminUser,
                    'ADMIN_PASS_HASH' => password_hash($adminPass, PASSWORD_BCRYPT),
                ];
                if (!writeConfigLocal($config, $configLocalFile)) {
                    $err = 'Ghi config.local.php thất bại. Check permission folder.';
                } else {
                    // Lock install
                    @file_put_contents($lockFile, date('Y-m-d H:i:s') . "\n" . ($_SERVER['REMOTE_ADDR'] ?? ''));
                    $_SESSION['install_data']['summary'] = [
                        'site_url'   => $config['SITE_URL'],
                        'site_name'  => $config['SITE_NAME'],
                        'admin_user' => $config['ADMIN_USERNAME'],
                        'imported'   => $_SESSION['install_data']['imported'] ?? 0,
                    ];
                    // Wipe sensitive
                    unset($_SESSION['install_data']['db']);
                    header('Location: install.php?step=5'); exit;
                }
            }
        }
    }
}

