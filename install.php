function h($s) { return htmlspecialchars((string)$s, ENT_QUOTES, 'UTF-8'); }
function genToken($bytes = 32) { return bin2hex(random_bytes($bytes)); }

function detectSiteUrl() {
    $proto = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
    $host  = $_SERVER['HTTP_HOST'] ?? 'localhost';
    $path  = rtrim(dirname($_SERVER['SCRIPT_NAME'] ?? '/'), '/\\');
    return $proto . '://' . $host . $path;
}

function testDbConnection($host, $name, $user, $pass) {
    try {
        $pdo = new PDO(
            "mysql:host={$host};dbname={$name};charset=utf8mb4",
            $user, $pass,
            [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
        );
        return ['ok' => true, 'pdo' => $pdo];
    } catch (PDOException $e) {
        return ['ok' => false, 'err' => $e->getMessage()];
    }
}

function importSqlFile(PDO $pdo, $sqlFile) {
    if (!is_file($sqlFile)) return ['ok' => false, 'err' => 'File schema không tìm thấy: ' . $sqlFile];
    $sql = file_get_contents($sqlFile);
    if ($sql === false) return ['ok' => false, 'err' => 'Đọc file schema thất bại'];

    // Split by ";" + filter blank/comment
    $stmts = [];
    foreach (preg_split('/;\s*\n/', $sql) as $stmt) {
        $stmt = trim($stmt);
        if ($stmt === '' || preg_match('/^(--|\/\*|SET |START |COMMIT|\/\*\!)/', $stmt)) continue;
        $stmts[] = $stmt;
    }
    try {
        foreach ($stmts as $s) $pdo->exec($s);
        return ['ok' => true, 'count' => count($stmts)];
    } catch (PDOException $e) {
        return ['ok' => false, 'err' => $e->getMessage()];
    }
}

function writeConfigLocal(array $data, $targetFile) {
    $lines = ["<?php", "// HCLOU-LICENSE — config.local.php (auto-generated by install.php)", "// KHÔNG commit file này vào git. Mọi secret production ở đây.", ""];
    foreach ($data as $k => $v) {
        $val = is_int($v) ? (string)$v : "'" . str_replace("'", "\\'", (string)$v) . "'";
        $lines[] = "define('{$k}', {$val});";
    }
    $lines[] = "";
    return file_put_contents($targetFile, implode("\n", $lines)) !== false;
}

